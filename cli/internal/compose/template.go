// Render produces the docker-compose.yaml text for a Spec.
//
// Two shapes, selected by Spec.DLPMode:
//
//   - DLPModeOff (default) / DLPModeOn — one service named "serving",
//     publishes HostPort on the host, model reachable directly. The
//     original v1 shape.
//   - DLPModeEnforce — two services: "serving" (NOT published, only on
//     the compose default network) and "dlp" (publishes HostPort → the
//     DLP proxy's container port). The model has no reachable host port;
//     the DLP proxy is the only door. Compose's default bridge network
//     is the enforcement mechanism.
//
// Determinism: env keys are emitted in alphabetical order in both shapes
// so the file hashes stably across runs.
func Render(s Spec) string {
	if s.Name == "" {
		s.Name = "bairav-model"
	}
	hostPort := s.HostPort
	if hostPort == 0 {
		hostPort = DefaultContainerPort
	}

	var b strings.Builder
	b.WriteString("# Generated by `bairav model deploy --target docker`.\n")
	fmt.Fprintf(&b, "# Stack: %s   Repo: %s   DLP: %s\n", s.Name, s.Repo, effectiveDLPMode(s.DLPMode))
	b.WriteString("# DO NOT EDIT BY HAND. Re-run `bairav model deploy` to update.\n")
	b.WriteString("services:\n")

	if s.IsCloud() {
		// The gateway is the DLP layer; --dlp has nothing to add.
		renderGatewayService(&b, s, hostPort)
	} else if s.DLPMode == DLPModeEnforce {
		renderServingService(&b, s /*publishHost*/, false)
		renderDLPService(&b, s, hostPort)
	} else {
		renderServingService(&b, s /*publishHost*/, true)
	}
	writeSharedNetworkDecl(&b)
	return b.String()
}

// ModelNetAlias is the DNS name a model is reachable at on the shared
// `bairav` docker network. Agents on the docker target resolve Models
// through this alias.
func ModelNetAlias(name string) string { return "model-" + name }

// modelNetEndpoint is the URL other containers on the shared network use.
// In enforce mode the alias sits on the DLP proxy, so the port is the
// proxy's — the model itself never joins the shared network.
func modelNetEndpoint(s Spec) string {
	port := DefaultContainerPort
	if s.DLPMode == DLPModeEnforce {
		port = DefaultDLPContainerPort
	}
	return fmt.Sprintf("http://%s:%d/v1", ModelNetAlias(s.Name), port)
}

// effectiveDLPMode returns the mode we'll act on, treating the empty
// string as "off" (so a zero Spec still renders sensibly).
func effectiveDLPMode(m DLPMode) DLPMode {
	if m == "" {
		return DLPModeOff
	}
	return m
}

// renderServingService writes the serving:llama-server service block.
// When publishHost is true the container's port is exposed on the host
// (single-service shape). When false the port is only reachable inside
// the compose network (enforce-mode shape — the DLP proxy is the only
// thing that can reach the model).
func renderServingService(b *strings.Builder, s Spec, publishHost bool) {
	env := map[string]string{
		"BAIRAV_REPO": s.Repo,
		"BAIRAV_PORT": fmt.Sprintf("%d", DefaultContainerPort),
		"BAIRAV_HOST": "0.0.0.0",
	}
	if s.File != "" {
		env["BAIRAV_FILE"] = s.File
	}
	if s.Revision != "" && s.Revision != "main" {
		env["BAIRAV_REVISION"] = s.Revision
	}
	if s.SHA256 != "" {
		env["BAIRAV_SHA256"] = s.SHA256
	}
	if s.CtxSize > 0 {
		env["BAIRAV_CTX_SIZE"] = fmt.Sprintf("%d", s.CtxSize)
	}
	if s.HFToken != "" {
		env["HF_TOKEN"] = s.HFToken
	}

	fmt.Fprintln(b, "  serving:")
	fmt.Fprintf(b, "    image: %s\n", s.image())
	fmt.Fprintf(b, "    container_name: bairav-%s\n", s.Name)
	fmt.Fprintln(b, "    restart: unless-stopped")
	fmt.Fprintln(b, "    environment:")
	for _, k := range sortedKeys(env) {
		fmt.Fprintf(b, "      %s: %q\n", k, env[k])
	}
	if publishHost {
		hostPort := s.HostPort
		if hostPort == 0 {
			hostPort = DefaultContainerPort
		}
		fmt.Fprintln(b, "    ports:")
		fmt.Fprintf(b, "      - %q\n", portMapping(hostPort, DefaultContainerPort))
	} else {
		// Enforce mode: no host-published port. `expose` documents intent
		// (only reachable within the compose network) — compose treats
		// this as documentation-only but it's the right signal to future
		// maintainers reading the generated file.
		fmt.Fprintln(b, "    expose:")
		fmt.Fprintf(b, "      - %q\n", fmt.Sprintf("%d", DefaultContainerPort))
	}
	fmt.Fprintln(b, "    volumes:")
	fmt.Fprintf(b, "      - %q\n", fmt.Sprintf("%s:/models", s.ModelsHostDir))
	fmt.Fprintln(b, "    labels:")
	fmt.Fprintf(b, "      %s: %q\n", LabelManaged, "true")
	fmt.Fprintf(b, "      %s: %q\n", LabelName, s.Name)
	fmt.Fprintf(b, "      %s: %q\n", LabelRepo, s.Repo)
	fmt.Fprintf(b, "      %s: %q\n", LabelRole, RoleServing)
	fmt.Fprintf(b, "      %s: %q\n", LabelKind, KindModel)
	if publishHost {
		// Off mode: the model itself is the door on the shared network.
		fmt.Fprintf(b, "      %s: %q\n", LabelEndpoint, modelNetEndpoint(s))
		writeServiceNetworks(b, ModelNetAlias(s.Name))
	}
	// Enforce mode: serving stays on the stack's private default network
	// only — joining the shared network would give Agents a DLP bypass.
	// llama-server takes a minute to load on first boot; give it plenty
	// of slack before compose marks it unhealthy.
	fmt.Fprintln(b, "    healthcheck:")
	fmt.Fprintf(b, "      test: [\"CMD\", \"curl\", \"-fsS\", \"http://127.0.0.1:%d/health\"]\n", DefaultContainerPort)
	fmt.Fprintln(b, "      interval: 10s")
	fmt.Fprintln(b, "      timeout: 3s")
	fmt.Fprintln(b, "      retries: 60")
	fmt.Fprintln(b, "      start_period: 30s")
}

// renderDLPService writes the dlp:bairav-cli service block. Only emitted
// in enforce mode. The proxy container consumes BAIRAV_DLP_* env vars
// (image entrypoint translates them into `bairav dlp serve` flags) and
// mounts an optional policy file read-only.
func renderDLPService(b *strings.Builder, s Spec, hostPort int) {
	image := s.DLPImage
	if image == "" {
		image = DefaultDLPImage
	}
	action := s.DLPAction
	if action == "" {
		action = "redact"
	}

	env := map[string]string{
		// serving:8080 is compose's internal DNS name for the sibling
		// service — the DLP proxy talks to the model over the compose
		// network, not via the host.
		"BAIRAV_DLP_UPSTREAM": fmt.Sprintf("http://serving:%d/v1", DefaultContainerPort),
		"BAIRAV_DLP_LISTEN":   fmt.Sprintf(":%d", DefaultDLPContainerPort),
		"BAIRAV_DLP_ACTION":   action,
		// Log audit records to stdout so `docker logs -f bairav-<name>-dlp | jq`
		// shows the live audit stream. Writing to a file inside the container
		// would require a writable path for the distroless nonroot user; stdout
		// is the 12-factor answer and dodges the whole class of perms issues.
		"BAIRAV_DLP_AUDIT": "-",
	}
	if s.DLPPolicyHostPath != "" {
		env["BAIRAV_DLP_POLICY"] = "/etc/bairav/dlp-policy.yaml"
	}

	fmt.Fprintln(b, "  dlp:")
	fmt.Fprintf(b, "    image: %s\n", image)
	fmt.Fprintf(b, "    container_name: bairav-%s-dlp\n", s.Name)
	fmt.Fprintln(b, "    restart: unless-stopped")
	fmt.Fprintln(b, "    depends_on:")
	fmt.Fprintln(b, "      - serving")
	fmt.Fprintln(b, "    environment:")
	for _, k := range sortedKeys(env) {
		fmt.Fprintf(b, "      %s: %q\n", k, env[k])
	}
	fmt.Fprintln(b, "    ports:")
	fmt.Fprintf(b, "      - %q\n", portMapping(hostPort, DefaultDLPContainerPort))
	if s.DLPPolicyHostPath != "" {
		fmt.Fprintln(b, "    volumes:")
		// :ro means read-only — the container should never mutate the
		// user's source-of-truth policy file.
		fmt.Fprintf(b, "      - %q\n", fmt.Sprintf("%s:/etc/bairav/dlp-policy.yaml:ro", s.DLPPolicyHostPath))
	}
	fmt.Fprintln(b, "    labels:")
	fmt.Fprintf(b, "      %s: %q\n", LabelManaged, "true")
	fmt.Fprintf(b, "      %s: %q\n", LabelName, s.Name)
	fmt.Fprintf(b, "      %s: %q\n", LabelRepo, s.Repo)
	fmt.Fprintf(b, "      %s: %q\n", LabelRole, RoleDLP)
	fmt.Fprintf(b, "      %s: %q\n", LabelKind, KindModel)
	fmt.Fprintf(b, "      %s: %q\n", LabelEndpoint, modelNetEndpoint(s))
	writeServiceNetworks(b, ModelNetAlias(s.Name))
}

// writeServiceNetworks puts a service on its stack's default network plus
// the shared `bairav` network under the given alias. Written at
// service-key indentation, so it can sit anywhere inside a service block.
func writeServiceNetworks(b *strings.Builder, alias string) {
	fmt.Fprintln(b, "    networks:")
	fmt.Fprintln(b, "      default: {}")
	fmt.Fprintf(b, "      %s:\n", SharedNetwork)
	fmt.Fprintf(b, "        aliases: [%q]\n", alias)
}

// writeSharedNetworkDecl declares the shared network as external (created
// once by EnsureNetwork, shared by every bairav stack on the host).
func writeSharedNetworkDecl(b *strings.Builder) {
	fmt.Fprintln(b, "networks:")
	fmt.Fprintf(b, "  %s:\n", SharedNetwork)
	fmt.Fprintln(b, "    external: true")
	fmt.Fprintf(b, "    name: %s\n", SharedNetwork)
}

// sortedKeys returns the keys of m in ascending order.
func sortedKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
