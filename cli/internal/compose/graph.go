// FindDoor returns the stack's door container (the one carrying a
// shared-network endpoint) for a given kind + name, or nil.
func FindDoor(stacks []Stack, kind, name string) *Stack {
	for i := range stacks {
		s := &stacks[i]
		if s.Kind == kind && s.Name == name && s.NetEndpoint != "" {
			return s
		}
	}
	return nil
}

// FindAny returns any container for kind + name (door or not), or nil.
// Used to tell "not deployed" apart from "deployed before Day 20, so it
// never joined the shared network".
func FindAny(stacks []Stack, kind, name string) *Stack {
	for i := range stacks {
		if stacks[i].Kind == kind && stacks[i].Name == name {
			return &stacks[i]
		}
	}
	return nil
}

// DependentAgents returns the names of Agent stacks referencing a Model
// (refPrefix = LabelRefModelPrefix) or Skill (LabelRefSkillPrefix).
func DependentAgents(stacks []Stack, refPrefix, name string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range stacks {
		if s.Kind != KindAgent || s.Role != RoleAgent {
			continue
		}
		if s.Labels[refPrefix+name] == "true" && !seen[s.Name] {
			seen[s.Name] = true
			out = append(out, s.Name)
		}
	}
	sort.Strings(out)
	return out
}

// -----------------------------------------------------------------------------
// small render helpers
// -----------------------------------------------------------------------------

func writeEnv(b *strings.Builder, env map[string]string) {
	if len(env) == 0 {
		return
	}
	fmt.Fprintln(b, "    environment:")
	for _, k := range sortedKeys(env) {
		fmt.Fprintf(b, "      %s: %q\n", k, env[k])
	}
}

// writePorts publishes containerPort on hostPort, or on a docker-chosen
// free host port when hostPort is 0. Always bound to PublishAddr.
func writePorts(b *strings.Builder, hostPort, containerPort int) {
	fmt.Fprintln(b, "    ports:")
	fmt.Fprintf(b, "      - %q\n", portMapping(hostPort, containerPort))
}

// PublishAddr is the host address stacks publish on: loopback by default,
// so a model, agent, or cloud gateway (which holds a provider key) isn't
// reachable from the coffee-shop Wi-Fi. BAIRAV_PUBLISH_ADDR=0.0.0.0 opts
// in to LAN access.
func PublishAddr() string {
	if v := os.Getenv("BAIRAV_PUBLISH_ADDR"); v != "" {
		return v
	}
	return "127.0.0.1"
}

// portMapping renders a compose short-syntax port: "addr:host:container",
// or "addr::container" for a docker-chosen host port.
func portMapping(hostPort, containerPort int) string {
	if hostPort > 0 {
		return fmt.Sprintf("%s:%d:%d", PublishAddr(), hostPort, containerPort)
	}
	return fmt.Sprintf("%s::%d", PublishAddr(), containerPort)
}

// hostPortOf extracts the host port from a short-syntax mapping
// ("8080:8080", "127.0.0.1:8080:8080"); 0 when there is none.
func hostPortOf(mapping string) (int, bool, error) {
	parts := strings.Split(mapping, ":")
	if len(parts) < 2 {
		return 0, false, nil
	}
	h := parts[len(parts)-2]
	if h == "" {
		return 0, false, nil
	}
	n, err := strconv.Atoi(h)
	return n, true, err
}

func sortedModels(ms []ResolvedModel) []ResolvedModel {
	out := append([]ResolvedModel(nil), ms...)
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}
