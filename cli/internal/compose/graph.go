package compose

// Day 20: Docker Compose parity for Skills and Agents.
//
// The K8s target wires the graph with Service DNS + the operator. The
// docker target has no controller, so it wires the graph with:
//
//   - one shared user-defined bridge network, `bairav`, that every stack
//     joins (created on demand by EnsureNetwork);
//   - a stable network alias per door container (model-<n>, skill-<n>,
//     agent-<n>) so containers find each other by name;
//   - labels on each door container carrying its in-network endpoint,
//     so `agent deploy --target docker` resolves refs from `docker ps`
//     alone. No state file to drift from reality.
//
// Resolution happens once, at deploy time. There is no live WaitingForDeps
// on the docker target: if a Model stack goes away later, the Agent keeps
// running with a dead endpoint until it's redeployed. That gap is the
// honest cost of not running a controller on the laptop.

import (
	"context"
	"fmt"
	"io"
	"os"
	"sort"
	"strconv"
	"strings"
)

// SharedNetwork is the docker network every bairav stack joins.
const SharedNetwork = "bairav"

// Day 20 label keys (see compose.go for the original set).
const (
	// LabelKind is model | skill | agent.
	LabelKind = "bairav.kind"
	// LabelEndpoint is the door container's URL on the shared network.
	LabelEndpoint = "bairav.endpoint"
	// LabelTransport is a Skill's MCP transport (sse | http).
	LabelTransport = "bairav.transport"
	// LabelRefModelPrefix / LabelRefSkillPrefix mark an Agent's refs, one
	// label per ref ("bairav.ref.model.qwen=true"). One label per ref rather
	// than a comma list because parseLabels splits docker's label string on
	// commas.
	LabelRefModelPrefix = "bairav.ref.model."
	LabelRefSkillPrefix = "bairav.ref.skill."

	KindModel = "model"
	KindSkill = "skill"
	KindAgent = "agent"

	RoleSkill = "skill"
	RoleAgent = "agent"
)

// SkillStackName is the on-disk dir + compose project name for a Skill.
// Namespaced so a Skill and an Agent (or Model) with the same name never
// collide. Model stacks keep their bare name for backwards compatibility.
func SkillStackName(name string) string { return "skill-" + name }

// AgentStackName is the on-disk dir + compose project name for an Agent.
func AgentStackName(name string) string { return "agent-" + name }

// SkillNetAlias is a Skill's DNS name on the shared network.
func SkillNetAlias(name string) string { return "skill-" + name }

// AgentNetAlias is an Agent's DNS name on the shared network.
func AgentNetAlias(name string) string { return "agent-" + name }

// EnvKey mirrors the operator's envKey: "qwen2-5-0-5b" → "QWEN2_5_0_5B".
// Kept identical so agent code reads the same env var names on both targets.
func EnvKey(name string) string {
	return strings.ReplaceAll(strings.ToUpper(name), "-", "_")
}

// -----------------------------------------------------------------------------
// Skill
// -----------------------------------------------------------------------------

// SkillSpec is one MCP server on the docker target. Mirrors SkillSpec on
// the CRD.
type SkillSpec struct {
	Name      string
	Image     string
	Transport string // sse | http
	Port      int    // container port
	// HostPort publishes the Skill on the host. 0 = docker picks a free
	// port (see `bairav ps`), so several Skills never fight over 3000.
	HostPort int
	Env      map[string]string
}

// SkillNetEndpoint is the Skill's URL on the shared network.
func SkillNetEndpoint(name string, port int) string {
	return fmt.Sprintf("http://%s:%d", SkillNetAlias(name), port)
}

// RenderSkill produces the compose file for a Skill stack.
func RenderSkill(s SkillSpec) string {
	port := s.Port
	if port == 0 {
		port = 3000
	}
	transport := s.Transport
	if transport == "" {
		transport = "sse"
	}
	var b strings.Builder
	b.WriteString("# Generated by `bairav skill deploy --target docker`.\n")
	fmt.Fprintf(&b, "# Skill: %s   Image: %s\n", s.Name, s.Image)
	b.WriteString("# DO NOT EDIT BY HAND. Re-run `bairav skill deploy` to update.\n")
	b.WriteString("services:\n")
	fmt.Fprintln(&b, "  skill:")
	fmt.Fprintf(&b, "    image: %s\n", s.Image)
	fmt.Fprintf(&b, "    container_name: bairav-%s\n", SkillStackName(s.Name))
	fmt.Fprintln(&b, "    restart: unless-stopped")
	writeEnv(&b, s.Env)
	writePorts(&b, s.HostPort, port)
	fmt.Fprintln(&b, "    labels:")
	fmt.Fprintf(&b, "      %s: %q\n", LabelManaged, "true")
	fmt.Fprintf(&b, "      %s: %q\n", LabelName, s.Name)
	fmt.Fprintf(&b, "      %s: %q\n", LabelKind, KindSkill)
	fmt.Fprintf(&b, "      %s: %q\n", LabelRole, RoleSkill)
	fmt.Fprintf(&b, "      %s: %q\n", LabelTransport, transport)
	fmt.Fprintf(&b, "      %s: %q\n", LabelEndpoint, SkillNetEndpoint(s.Name, port))
	writeServiceNetworks(&b, SkillNetAlias(s.Name))
	writeSharedNetworkDecl(&b)
	return b.String()
}

// UpSkill renders + brings up a Skill stack.
func UpSkill(ctx context.Context, s SkillSpec, stdout, stderr io.Writer) error {
	if s.Name == "" || s.Image == "" {
		return fmt.Errorf("compose: skill name and image are required")
	}
	if err := validateRender(s.Image, s.Env); err != nil {
		return err
	}
	return upStack(ctx, SkillStackName(s.Name), RenderSkill(s), stdout, stderr)
}

// -----------------------------------------------------------------------------
// Agent
// -----------------------------------------------------------------------------

// ResolvedModel is a Model ref already looked up via List.
type ResolvedModel struct {
	Name     string
	Endpoint string // shared-network URL, e.g. http://model-qwen:8080/v1
}

// ResolvedSkill is a Skill ref already looked up via List.
type ResolvedSkill struct {
	Name      string
	Endpoint  string
	Transport string
}

// AgentDLP enables one DLP proxy service per Model inside the Agent stack
// — the docker-target twin of the K8s DLP sidecar (Day 18).
type AgentDLP struct {
	Image          string   // default DefaultDLPImage
	Packs          []string // empty → "none" (built-ins only)
	Action         string   // redact | block | audit (default redact)
	Direction      string   // request | response | both (default both)
	PolicyHostPath string   // optional absolute path, mounted read-only
}

// AgentSpec is one user agent container on the docker target.
type AgentSpec struct {
	Name     string
	Image    string
	Port     int // container port
	HostPort int // 0 = docker picks
	Env      map[string]string
	Models   []ResolvedModel
	Skills   []ResolvedSkill
	DLP      *AgentDLP // nil = no DLP services
}

// AgentNetEndpoint is the Agent's own URL on the shared network.
func AgentNetEndpoint(name string, port int) string {
	return fmt.Sprintf("http://%s:%d", AgentNetAlias(name), port)
}

// dlpServiceName is the compose service (and DNS name inside the Agent
// stack's private network) of the DLP proxy fronting one Model.
func dlpServiceName(model string) string { return "dlp-" + model }

// AgentModelEndpoints returns the URL the agent container gets for each
// Model: the Model's shared-network endpoint, or the in-stack DLP proxy
// when DLP is on. Exported for tests + the deploy banner.
func AgentModelEndpoints(s AgentSpec) map[string]string {
	out := make(map[string]string, len(s.Models))
	for _, m := range s.Models {
		if s.DLP != nil {
			out[m.Name] = fmt.Sprintf("http://%s:%d/v1", dlpServiceName(m.Name), DefaultDLPContainerPort)
		} else {
			out[m.Name] = m.Endpoint
		}
	}
	return out
}

// RenderAgent produces the compose file for an Agent stack.
func RenderAgent(s AgentSpec) string {
	port := s.Port
	if port == 0 {
		port = 8000
	}
	endpoints := AgentModelEndpoints(s)

	env := map[string]string{}
	for k, v := range s.Env {
		env[k] = v
	}
	for _, m := range s.Models {
		env[fmt.Sprintf("BAIRAV_MODEL_%s_ENDPOINT", EnvKey(m.Name))] = endpoints[m.Name]
	}
	for _, sk := range s.Skills {
		env[fmt.Sprintf("BAIRAV_SKILL_%s_ENDPOINT", EnvKey(sk.Name))] = sk.Endpoint
		env[fmt.Sprintf("BAIRAV_SKILL_%s_TRANSPORT", EnvKey(sk.Name))] = sk.Transport
	}

	var b strings.Builder
	b.WriteString("# Generated by `bairav agent deploy --target docker`.\n")
	fmt.Fprintf(&b, "# Agent: %s   Image: %s   DLP: %v\n", s.Name, s.Image, s.DLP != nil)
	b.WriteString("# DO NOT EDIT BY HAND. Re-run `bairav agent deploy` to update.\n")
	b.WriteString("services:\n")
	fmt.Fprintln(&b, "  agent:")
	fmt.Fprintf(&b, "    image: %s\n", s.Image)
	fmt.Fprintf(&b, "    container_name: bairav-%s\n", AgentStackName(s.Name))
	fmt.Fprintln(&b, "    restart: unless-stopped")
	if s.DLP != nil && len(s.Models) > 0 {
		fmt.Fprintln(&b, "    depends_on:")
		for _, m := range sortedModels(s.Models) {
			fmt.Fprintf(&b, "      - %s\n", dlpServiceName(m.Name))
		}
	}
	writeEnv(&b, env)
	writePorts(&b, s.HostPort, port)
	fmt.Fprintln(&b, "    labels:")
	agentLabels := map[string]string{
		LabelManaged:  "true",
		LabelName:     s.Name,
		LabelKind:     KindAgent,
		LabelRole:     RoleAgent,
		LabelEndpoint: AgentNetEndpoint(s.Name, port),
	}
	for _, m := range s.Models {
		agentLabels[LabelRefModelPrefix+m.Name] = "true"
	}
	for _, sk := range s.Skills {
		agentLabels[LabelRefSkillPrefix+sk.Name] = "true"
	}
	for _, k := range sortedKeys(agentLabels) {
		fmt.Fprintf(&b, "      %s: %q\n", k, agentLabels[k])
	}
	writeServiceNetworks(&b, AgentNetAlias(s.Name))

	if s.DLP != nil {
		for _, m := range sortedModels(s.Models) {
			renderAgentDLPService(&b, s, m)
		}
	}
	writeSharedNetworkDecl(&b)
	return b.String()
}

func renderAgentDLPService(b *strings.Builder, s AgentSpec, m ResolvedModel) {
	d := s.DLP
	image := d.Image
	if image == "" {
		image = DefaultDLPImage
	}
	action := d.Action
	if action == "" {
		action = "redact"
	}
	direction := d.Direction
	if direction == "" {
		direction = "both"
	}
	packs := "none"
	if len(d.Packs) > 0 {
		packs = strings.Join(d.Packs, ",")
	}
	env := map[string]string{
		"BAIRAV_DLP_UPSTREAM":  m.Endpoint,
		"BAIRAV_DLP_LISTEN":    fmt.Sprintf(":%d", DefaultDLPContainerPort),
		"BAIRAV_DLP_ACTION":    action,
		"BAIRAV_DLP_DIRECTION": direction,
		"BAIRAV_DLP_AUDIT":     "-",
		"BAIRAV_DLP_PACK":      packs,
	}
	if d.PolicyHostPath != "" {
		env["BAIRAV_DLP_POLICY"] = "/etc/bairav/dlp-policy.yaml"
	}
	svc := dlpServiceName(m.Name)
	fmt.Fprintf(b, "  %s:\n", svc)
	fmt.Fprintf(b, "    image: %s\n", image)
	fmt.Fprintf(b, "    container_name: bairav-%s-%s\n", AgentStackName(s.Name), svc)
	fmt.Fprintln(b, "    restart: unless-stopped")
	writeEnv(b, env)
	if d.PolicyHostPath != "" {
		fmt.Fprintln(b, "    volumes:")
		fmt.Fprintf(b, "      - %q\n", d.PolicyHostPath+":/etc/bairav/dlp-policy.yaml:ro")
	}
	fmt.Fprintln(b, "    labels:")
	fmt.Fprintf(b, "      %s: %q\n", LabelManaged, "true")
	fmt.Fprintf(b, "      %s: %q\n", LabelName, s.Name)
	fmt.Fprintf(b, "      %s: %q\n", LabelKind, KindAgent)
	fmt.Fprintf(b, "      %s: %q\n", LabelRole, RoleDLP)
	// The DLP proxy needs the shared network to reach the Model, and the
	// stack's default network so the agent reaches it as dlp-<model>. It
	// gets no shared-network alias: nothing outside this stack should use it.
	fmt.Fprintln(b, "    networks:")
	fmt.Fprintln(b, "      default: {}")
	fmt.Fprintf(b, "      %s: {}\n", SharedNetwork)
}

// UpAgent renders + brings up an Agent stack.
func UpAgent(ctx context.Context, s AgentSpec, stdout, stderr io.Writer) error {
	if s.Name == "" || s.Image == "" {
		return fmt.Errorf("compose: agent name and image are required")
	}
	if err := validateRender(s.Image, s.Env); err != nil {
		return err
	}
	if s.DLP != nil {
		if err := validateRender(s.DLP.Image, nil); err != nil {
			return err
		}
	}
	return upStack(ctx, AgentStackName(s.Name), RenderAgent(s), stdout, stderr)
}

